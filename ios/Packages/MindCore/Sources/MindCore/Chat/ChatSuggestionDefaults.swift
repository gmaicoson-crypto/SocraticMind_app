    static func items(_ context: ChatSuggestionContext, excluding: [String] = []) -> [String] {
        let pool: [String] = if context.target
            .mode == .socratic
        {
            context.target.topicID > 0 ? socratic_topic : socratic_new
        } else {
            context.hasConversation ? normal_followup : normal_new
        }
        return Array(pool.filter { !excluding.contains($0) }.prefix(12))
    }
